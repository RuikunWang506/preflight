"""Does an install fetch a package from the registry, or use the project's own copy?
(lookfirst/scanners/lockfiles.py: the check that keeps a local package that shares its name
with npm malware from being called malware.)"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from lookfirst.scanners.lockfiles import fetched_from_registry

NPM_URL = "https://registry.npmjs.org/{0}/-/{0}-{1}.tgz"


def write(root: Path, name: str, text: str) -> str:
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return name


def package_lock(packages: dict) -> str:
    return json.dumps({"lockfileVersion": 3, "packages": {"": {"name": "app"}, **packages}})


@pytest.mark.parametrize(
    ("packages", "fetched"),
    [
        (
            {"node_modules/rc": {"version": "1.2.9", "resolved": NPM_URL.format("rc", "1.2.9")}},
            True,
        ),
        ({"node_modules/rc": {"version": "1.2.9", "integrity": "sha512-abc"}}, True),
        ({"node_modules/rc": {"resolved": "packages/rc", "link": True}}, False),
        ({"packages/rc": {"name": "rc", "version": "1.2.9"}}, False),  # a workspace
        ({"node_modules/rc": {"version": "1.2.9", "resolved": "file:../rc"}}, False),
        ({"node_modules/other": {"version": "1.0.0"}}, None),
    ],
)
def test_package_lock(tmp_path: Path, packages: dict, fetched: bool | None) -> None:
    lock = write(tmp_path, "package-lock.json", package_lock(packages))
    assert fetched_from_registry(tmp_path, lock, "rc", "1.2.9") is fetched


def test_package_lock_v1(tmp_path: Path) -> None:
    deps = {
        "rc": {"version": "1.2.9", "resolved": NPM_URL.format("rc", "1.2.9")},
        "mine": {"version": "file:../mine"},
    }
    lock = write(tmp_path, "npm-shrinkwrap.json", json.dumps({"dependencies": deps}))
    assert fetched_from_registry(tmp_path, lock, "rc", "1.2.9") is True
    assert fetched_from_registry(tmp_path, lock, "mine", "file:../mine") is False


YARN_V1 = """# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"eslint-plugin-react-internal@link:./scripts/eslint-rules":
  version "0.0.0"
  uid ""

fsevents@^1.0.0, fsevents@^1.0.17:
  version "1.1.2"
  resolved "https://registry.yarnpkg.com/fsevents/-/fsevents-1.1.2.tgz#3282b713fb3ad80ede0e9fcf4611b5aa6fc033f4"
  dependencies:
    nan "^2.3.0"

"@scope/pkg@^2.0.0":
  version "2.1.0"
  resolved "https://registry.yarnpkg.com/@scope/pkg/-/pkg-2.1.0.tgz"
"""

YARN_BERRY = """__metadata:
  version: 8

"lodash@npm:^4.17.15":
  version: 4.17.15
  resolution: "lodash@npm:4.17.15"

"my-tools@workspace:packages/tools":
  version: 0.0.0-use.local
  resolution: "my-tools@workspace:packages/tools"
"""


@pytest.mark.parametrize(
    ("text", "name", "version", "fetched"),
    [
        (YARN_V1, "eslint-plugin-react-internal", "0.0.0", False),
        (YARN_V1, "fsevents", "1.1.2", True),
        (YARN_V1, "@scope/pkg", "2.1.0", True),
        (YARN_V1, "fsevents", "9.9.9", None),
        (YARN_BERRY, "lodash", "4.17.15", True),
        (YARN_BERRY, "my-tools", "0.0.0-use.local", False),
    ],
)
def test_yarn(tmp_path: Path, text: str, name: str, version: str, fetched: bool | None) -> None:
    lock = write(tmp_path, "yarn.lock", text)
    assert fetched_from_registry(tmp_path, lock, name, version) is fetched


PNPM_V9 = """lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      local-thing:
        specifier: link:../local-thing
        version: link:../local-thing
      rc:
        specifier: ^1.2.0
        version: 1.2.9

packages:

  rc@1.2.9:
    resolution: {integrity: sha512-abc}
"""


@pytest.mark.parametrize(
    ("name", "version", "fetched"),
    [("rc", "1.2.9", True), ("local-thing", "0.0.0", False), ("other", "1.0.0", None)],
)
def test_pnpm(tmp_path: Path, name: str, version: str, fetched: bool | None) -> None:
    lock = write(tmp_path, "pnpm-lock.yaml", PNPM_V9)
    assert fetched_from_registry(tmp_path, lock, name, version) is fetched


UV_LOCK = """version = 1

[[package]]
name = "my-app"
version = "0.1.0"
source = { editable = "." }

[[package]]
name = "PyYAML"
version = "5.3"
source = { registry = "https://pypi.org/simple" }
"""

POETRY_LOCK = """[[package]]
name = "requests"
version = "2.19.0"

[[package]]
name = "helper"
version = "1.0.0"

[package.source]
type = "directory"
url = "../helper"
"""

CARGO_LOCK = """version = 3

[[package]]
name = "my-crate"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""


@pytest.mark.parametrize(
    ("file", "text", "name", "version", "fetched"),
    [
        ("uv.lock", UV_LOCK, "pyyaml", "5.3", True),  # names compare the PyPI way
        ("uv.lock", UV_LOCK, "my_app", "0.1.0", False),
        ("poetry.lock", POETRY_LOCK, "requests", "2.19.0", True),
        ("poetry.lock", POETRY_LOCK, "helper", "1.0.0", False),
        ("Cargo.lock", CARGO_LOCK, "serde", "1.0.0", True),
        ("Cargo.lock", CARGO_LOCK, "my-crate", "0.1.0", False),
    ],
)
def test_toml_lockfiles(
    tmp_path: Path, file: str, text: str, name: str, version: str, fetched: bool
) -> None:
    lock = write(tmp_path, file, text)
    assert fetched_from_registry(tmp_path, lock, name, version) is fetched


def test_pipfile_lock(tmp_path: Path) -> None:
    data = {
        "default": {"requests": {"version": "==2.19.0"}, "mine": {"path": ".", "editable": True}}
    }
    lock = write(tmp_path, "Pipfile.lock", json.dumps(data))
    assert fetched_from_registry(tmp_path, lock, "requests", "2.19.0") is True
    assert fetched_from_registry(tmp_path, lock, "mine", "0") is False


@pytest.mark.parametrize(
    ("name", "text"),
    [
        ("package-lock.json", "{not json"),
        ("uv.lock", "[[package]\nbroken"),
        ("requirements.txt", "rc==1.2.9\n"),  # pip installs from the index: can't tell otherwise
        ("go.sum", "example.com/x v1.0.0 h1:abc=\n"),
    ],
)
def test_anything_unexpected_means_cant_tell(tmp_path: Path, name: str, text: str) -> None:
    lock = write(tmp_path, name, text)
    assert fetched_from_registry(tmp_path, lock, "rc", "1.2.9") is None


def test_paths_outside_the_project_and_links_are_never_read(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "yarn.lock").write_text(YARN_V1)
    root = tmp_path / "project"
    root.mkdir()
    (root / "yarn.lock").symlink_to(outside / "yarn.lock")
    assert fetched_from_registry(root, "../outside/yarn.lock", "fsevents", "1.1.2") is None
    assert fetched_from_registry(root, "yarn.lock", "fsevents", "1.1.2") is None
    assert fetched_from_registry(root, "/etc/passwd", "x", "1") is None
